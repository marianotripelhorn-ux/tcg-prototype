import { describe,it,expect } from "vitest";
import { byId } from "../data";
import {
  startPvpGame,nextHumanSide,submitHumanPlay,submitHumanSpecial,submitHumanQuiero
} from "./game";
import { archivedSpecial,CREATOR_KIND,generateOnPlay } from "./manifestations";
import type { GameState } from "./types";
import type { Position } from "../types";

/** Start a complete duel without choosing cards via the UI. */
function duel(
  state:GameState,host:{card:string;pos:Position;daggers?:number},
  guest:{card:string;pos:Position;daggers?:number}
){
  state.player.hand[0]=byId(host.card);
  state.opponent.hand[0]=byId(guest.card);
  const first=nextHumanSide(state);
  expect(first==="player"||first==="opponent").toBe(true);
  if(first==="player"){
    submitHumanPlay(state,"player",0,host.pos,()=>.3,host.daggers||0);
    submitHumanPlay(state,"opponent",0,guest.pos,()=>.3,guest.daggers||0);
  }else{
    submitHumanPlay(state,"opponent",0,guest.pos,()=>.3,guest.daggers||0);
    submitHumanPlay(state,"player",0,host.pos,()=>.3,host.daggers||0);
  }
}

describe("Manifestaciones v0.1",()=>{
  it("classifies exactly the designated 16 generators",()=>{
    expect(Object.values(CREATOR_KIND).filter(k=>k==="dagger")).toHaveLength(5);
    expect(Object.values(CREATOR_KIND).filter(k=>k==="shield")).toHaveLength(3);
    expect(Object.values(CREATOR_KIND).filter(k=>k==="relic")).toHaveLength(4);
    expect(Object.values(CREATOR_KIND).filter(k=>k==="symmetry")).toHaveLength(4);
    expect(byId("caballero_tigre").trait).toBe("Portaanillos · Dextral");
    expect(byId("desencantador").trait).toBe("Portaanillos · Sinistral");
    expect(byId("huevo").trait).toBe("Objeto mágico");
    expect(byId("santo_bifronte").trait).toBe("Ambidiestro");
  });
  it("lets multiple Daggers boost one card and adds spent Daggers to Archive",()=>{
    const state=startPvpGame("dextral","sinistral",()=>.2,"player");
    state.player.specialHand.push("dagger","dagger");
    duel(state,{card:"caballero_tigre",pos:"diestra",daggers:2},{card:"protector",pos:"siniestra"});
    expect(state.lastDuel?.playerPlay.daggers).toBe(2);
    expect(state.lastDuel?.playerPlay.notes).toContain("+2 Daga Etérea");
    expect(state.player.archives.diestra.filter(c=>c.specialArchiveKind==="dagger")).toHaveLength(2);
    expect(state.player.specialHand).toEqual(["dagger"]); // generated by Caballero Tigre after duel
  });
  it("anchors a Shield after the creating duel and activates on the NEXT enemy card there",()=>{
    const state=startPvpGame("sinistral","dextral",()=>.2,"player");
    duel(state,{card:"protector",pos:"trono"},{card:"invocadagas",pos:"diestra"});
    expect(state.player.manifestations).toContainEqual({kind:"shield",position:"trono",createdRound:1});
    expect(state.lastDuel?.opponentPlay.notes?.some(n=>n.includes("Escudo Etéreo"))).toBe(false);
    duel(state,{card:"asesino_sinistral",pos:"siniestra"},{card:"guardia_castillo",pos:"trono"});
    expect(state.lastDuel?.opponentPlay.notes).toContain("−2 Escudo Etéreo");
    expect(state.player.manifestations.filter(t=>t.kind==="shield")).toHaveLength(0);
  });
  it("Relic produces +2 Archive after a duel with its lane unused and expires on round end",()=>{
    const state=startPvpGame("empireos","dextral",()=>.2,"player");
    state.player.specialHand.push("relic");
    submitHumanSpecial(state,"player","relic","trono");
    expect(state.player.specialHand).not.toContain("relic");
    duel(state,{card:"bibliotecario",pos:"siniestra"},{card:"caballero_tigre",pos:"diestra"});
    expect(state.player.archives.trono.filter(c=>c.specialArchiveKind==="relic")).toHaveLength(2);
    state.phase="awaiting_quiero";state.duelScore={player:0,opponent:2};
    submitHumanQuiero(state,"player",false,()=>.2);
    expect(state.round).toBe(2);
    expect(state.player.manifestations.filter(t=>t.kind==="relic")).toHaveLength(0);
    expect(state.player.archives.trono.filter(c=>c.specialArchiveKind==="relic")).toHaveLength(2);
  });
  it("Simetría copies visible enemy Shield or archived Dagger, not hidden cards",()=>{
    const state=startPvpGame("samas","dextral",()=>.2,"player");
    state.opponent.manifestations.push({kind:"shield",position:"diestra",createdRound:1});
    state.player.specialHand.push("symmetry");
    submitHumanSpecial(state,"player","symmetry",undefined,{kind:"shield",position:"diestra"});
    expect(state.player.manifestations).toContainEqual({kind:"shield",position:"diestra",createdRound:1});
    expect(state.player.specialHand).not.toContain("symmetry");
    state.player.specialHand.push("symmetry");
    expect(()=>submitHumanSpecial(state,"player","symmetry",undefined,{kind:"dagger",position:"siniestra"})).toThrow();
    state.opponent.archives.siniestra.push(archivedSpecial("dagger","red"));
    submitHumanSpecial(state,"player","symmetry",undefined,{kind:"dagger",position:"siniestra"});
    expect(state.player.specialHand).toContain("dagger");
  });
  it("only one Simetría Perfecta can be generated into a hand",()=>{
    const state=startPvpGame("samas","dextral",()=>.2,"player");
    generateOnPlay(state.player,byId("santo_bifronte"),"siniestra",1);
    generateOnPlay(state.player,byId("santo_gemelo"),"trono",1);
    expect(state.player.specialHand.filter(k=>k==="symmetry")).toHaveLength(1);
  });
});
